"""Export trained models to artefacts an ESP32-S3 (Arduino IDE / ESP-IDF) can compile.

* LightGBM  -> dependency-free C header (flattened node table + iterative traversal)
* Logistic  -> C header (coefficients)
* Keras MLP -> .h5 / .keras, TFLite float32 + full-int8, C byte array for TFLite Micro,
               and a dependency-free C header with float weights
* DSP spec  -> biquad coefficients and algorithm constants of edge_features.py
Every C header computes the same pipeline as Python: impute (median) -> [standardise] -> model ->
probability -> Platt recalibration -> threshold.
"""
import datetime
import subprocess
import textwrap
from pathlib import Path

import numpy as np

from . import edge_features as ef

HEADER_NOTE = "/* Auto-generated by ml/dgx/export.py on {date}. Do not edit by hand. */\n"


def _fmt(v, kind):
    if kind == "double":
        return repr(float(v))
    if kind == "float":
        return f"{float(v):.9g}f"
    return str(int(v))


def c_array(ctype, name, values, kind, per_line=6):
    vals = [_fmt(v, kind) for v in values]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    body = ",\n    ".join(lines)
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    {body}\n}};\n"


def _common_block(prefix, feature_names, medians, platt, thresholds, extra_scaler=None):
    s = [f"#define {prefix}_N_FEATURES {len(feature_names)}\n",
         f"/* feature order expected in the input array (units in the name; NAN = not measurable) */\n",
         f"static const char *const {prefix}_FEATURE_NAMES[{len(feature_names)}] = {{\n    "
         + ",\n    ".join(f'"{n}"' for n in feature_names) + "\n};\n",
         c_array("double", f"{prefix}_MEDIAN", medians, "double")]
    if extra_scaler is not None:
        s.append(c_array("double", f"{prefix}_MEAN", extra_scaler[0], "double"))
        s.append(c_array("double", f"{prefix}_SCALE", extra_scaler[1], "double"))
    s.append(f"#define {prefix}_PLATT_A {platt[0]!r}\n#define {prefix}_PLATT_B {platt[1]!r}\n")
    for k, v in thresholds.items():
        s.append(f"#define {prefix}_THRESHOLD_{k.upper()} {float(v)!r}  /* on the uncalibrated model score */\n")
    s.append(textwrap.dedent(f"""
        /* Platt-recalibrated probability (calibrated on development out-of-fold predictions) */
        static inline double {prefix.lower()}_calibrate(double score) {{
            if (score < 1e-6) score = 1e-6;
            if (score > 1.0 - 1e-6) score = 1.0 - 1e-6;
            double l = log(score / (1.0 - score));
            return 1.0 / (1.0 + exp(-({prefix}_PLATT_A * l + {prefix}_PLATT_B)));
        }}
    """))
    return "".join(s)


def _preamble(guard, title, meta):
    lines = [HEADER_NOTE.format(date=datetime.date.today().isoformat()),
             f"/* {title} */\n"]
    for k, v in meta.items():
        lines.append(f"/*   {k}: {v} */\n")
    lines.append(f"#ifndef {guard}\n#define {guard}\n#include <math.h>\n#include <stdint.h>\n\n")
    return "".join(lines)


# ------------------------------------------------------------------ LightGBM
def lgbm_to_c(booster, path, feature_names, medians, platt, thresholds, meta, prefix="DGX_GBM"):
    dump = booster.dump_model()
    assert dump["objective"].startswith("binary"), dump["objective"]
    feat, thr, left, right, leaf, roots = [], [], [], [], [], []

    def walk(node):
        if "split_index" not in node:
            leaf.append(node["leaf_value"])
            return ~(len(leaf) - 1)
        assert node["decision_type"] == "<=", node["decision_type"]
        i = len(feat)
        feat.append(node["split_feature"]), thr.append(node["threshold"]), left.append(0), right.append(0)
        left[i] = walk(node["left_child"])
        right[i] = walk(node["right_child"])
        return i

    for t in dump["tree_info"]:
        roots.append(walk(t["tree_structure"]))
    idx_t = "int16_t" if max(len(feat), len(leaf)) < 32767 else "int32_t"
    body = [_preamble(f"{prefix}_H", "Gradient-boosted trees (LightGBM) prediabetes risk model", meta),
            _common_block(prefix, feature_names, medians, platt, thresholds),
            f"\n#define {prefix}_N_TREES {len(roots)}\n#define {prefix}_N_NODES {len(feat)}\n#define {prefix}_N_LEAVES {len(leaf)}\n",
            c_array("uint8_t", f"{prefix}_FEAT", feat, "int", 16),
            c_array("double", f"{prefix}_THR", thr, "double", 4),
            c_array(idx_t, f"{prefix}_LEFT", left, "int", 12),
            c_array(idx_t, f"{prefix}_RIGHT", right, "int", 12),
            c_array("double", f"{prefix}_LEAF", leaf, "double", 4),
            c_array("int32_t", f"{prefix}_ROOT", roots, "int", 12),
            textwrap.dedent(f"""
            /* Returns the uncalibrated model probability. features[] in {prefix}_FEATURE_NAMES order; NAN = missing. */
            static inline double {prefix.lower()}_score(const float *features) {{
                double x[{prefix}_N_FEATURES];
                for (int i = 0; i < {prefix}_N_FEATURES; ++i)
                    x[i] = isnan(features[i]) ? {prefix}_MEDIAN[i] : (double)features[i];
                double raw = 0.0;
                for (int t = 0; t < {prefix}_N_TREES; ++t) {{
                    int32_t n = {prefix}_ROOT[t];
                    while (n >= 0)
                        n = (x[{prefix}_FEAT[n]] <= {prefix}_THR[n]) ? {prefix}_LEFT[n] : {prefix}_RIGHT[n];
                    raw += {prefix}_LEAF[~n];
                }}
                return 1.0 / (1.0 + exp(-raw));
            }}
            #endif /* {prefix}_H */
            """)]
    Path(path).write_text("".join(body))
    flash = len(feat) * (8 + 2 * (2 if idx_t == "int16_t" else 4) + 1) + len(leaf) * 8 + len(roots) * 4 + len(medians) * 8
    return {"trees": len(roots), "internal_nodes": len(feat), "leaves": len(leaf), "flash_bytes": flash}


# ------------------------------------------------------------------ logistic regression
def lr_to_c(pipeline, path, feature_names, platt, thresholds, meta, prefix="DGX_LR"):
    imp, sc, clf = pipeline.named_steps["impute"], pipeline.named_steps["scale"], pipeline.named_steps["clf"]
    body = [_preamble(f"{prefix}_H", "Logistic-regression prediabetes risk model", meta),
            _common_block(prefix, feature_names, imp.statistics_, platt, thresholds, (sc.mean_, sc.scale_)),
            c_array("double", f"{prefix}_COEF", clf.coef_[0], "double", 4),
            f"#define {prefix}_INTERCEPT {float(clf.intercept_[0])!r}\n",
            textwrap.dedent(f"""
            static inline double {prefix.lower()}_score(const float *features) {{
                double z = {prefix}_INTERCEPT;
                for (int i = 0; i < {prefix}_N_FEATURES; ++i) {{
                    double x = isnan(features[i]) ? {prefix}_MEDIAN[i] : (double)features[i];
                    z += {prefix}_COEF[i] * (x - {prefix}_MEAN[i]) / {prefix}_SCALE[i];
                }}
                return 1.0 / (1.0 + exp(-z));
            }}
            #endif /* {prefix}_H */
            """)]
    Path(path).write_text("".join(body))
    return {"parameters": int(clf.coef_.size + 1), "flash_bytes": int((clf.coef_.size + 1) * 8 + len(feature_names) * 24)}


# ------------------------------------------------------------------ Keras MLP -> pure C
def mlp_to_c(mlp, path, feature_names, platt, thresholds, meta, prefix="DGX_MLP"):
    dense = [l for l in mlp.model_.layers if l.__class__.__name__ == "Dense"]
    body = [_preamble(f"{prefix}_H", "Multilayer-perceptron prediabetes risk model (float32 weights)", meta),
            _common_block(prefix, feature_names, mlp.imputer_.statistics_, platt, thresholds,
                          (mlp.scaler_.mean_, mlp.scaler_.scale_))]
    widths = [len(feature_names)]
    for k, layer in enumerate(dense):
        W, b = layer.get_weights()
        widths.append(W.shape[1])
        body.append(c_array("float", f"{prefix}_W{k}", W.ravel(), "float", 6))   # row-major [in][out]
        body.append(c_array("float", f"{prefix}_B{k}", b, "float", 6))
    maxw = max(widths)
    layers_code = []
    for k in range(len(dense)):
        last = k == len(dense) - 1
        act = "" if last else "        if (s < 0.0f) s = 0.0f;  /* ReLU */\n"
        layers_code.append(
            f"    for (int o = 0; o < {widths[k + 1]}; ++o) {{\n"
            f"        float s = {prefix}_B{k}[o];\n"
            f"        for (int i = 0; i < {widths[k]}; ++i) s += a[i] * {prefix}_W{k}[i * {widths[k + 1]} + o];\n"
            f"{act}        b[o] = s;\n    }}\n"
            + ("" if last else f"    for (int i = 0; i < {widths[k + 1]}; ++i) a[i] = b[i];\n"))
    body.append(
        f"\nstatic inline double {prefix.lower()}_score(const float *features) {{\n"
        f"    float a[{maxw}], b[{maxw}];\n"
        f"    for (int i = 0; i < {prefix}_N_FEATURES; ++i) {{\n"
        f"        double x = isnan(features[i]) ? {prefix}_MEDIAN[i] : (double)features[i];\n"
        f"        double z = (x - {prefix}_MEAN[i]) / {prefix}_SCALE[i];\n"
        f"        a[i] = (float)(z > {mlp.CLIP!r} ? {mlp.CLIP!r} : (z < -{mlp.CLIP!r} ? -{mlp.CLIP!r} : z));  /* clip +/-{mlp.CLIP:g} SD */\n    }}\n"
        + "".join(layers_code)
        + "    return 1.0 / (1.0 + exp(-(double)b[0]));\n}\n"
        f"#endif /* {prefix}_H */\n")
    Path(path).write_text("".join(body))
    n_params = int(sum(np.prod(w.shape) for l in dense for w in l.get_weights()))
    return {"parameters": n_params, "flash_bytes": n_params * 4 + len(feature_names) * 24, "widths": widths}


# ------------------------------------------------------------------ Keras MLP -> TFLite
def keras_to_tflite(keras_model, X_representative, path_fp32, path_int8):
    import tensorflow as tf
    conv = tf.lite.TFLiteConverter.from_keras_model(keras_model)
    Path(path_fp32).write_bytes(conv.convert())
    conv = tf.lite.TFLiteConverter.from_keras_model(keras_model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    rep = np.asarray(X_representative, dtype=np.float32)

    def gen():
        for row in rep:
            yield [row[None, :]]

    conv.representative_dataset = gen
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    Path(path_int8).write_bytes(conv.convert())
    return {"fp32_bytes": Path(path_fp32).stat().st_size, "int8_bytes": Path(path_int8).stat().st_size}


def tflite_predict(path, X_std):
    import tensorflow as tf
    it = tf.lite.Interpreter(model_path=str(path))
    it.allocate_tensors()
    inp, out = it.get_input_details()[0], it.get_output_details()[0]
    X = np.asarray(X_std, dtype=np.float32)
    res = np.empty(len(X))
    for i, row in enumerate(X):
        if inp["dtype"] == np.int8:
            s, z = inp["quantization"]
            q = np.clip(np.round(row / s + z), -128, 127).astype(np.int8)
            it.set_tensor(inp["index"], q[None, :])
        else:
            it.set_tensor(inp["index"], row[None, :])
        it.invoke()
        o = it.get_tensor(out["index"])[0, 0]
        if out["dtype"] == np.int8:
            s, z = out["quantization"]
            o = (float(o) - z) * s
        res[i] = o
    return res, inp["quantization"], out["quantization"]


def tflite_to_c_array(tflite_path, header_path, var="g_dgx_mlp_int8", meta=None, quant=None):
    data = Path(tflite_path).read_bytes()
    hexes = [f"0x{b:02x}" for b in data]
    lines = [", ".join(hexes[i:i + 12]) for i in range(0, len(hexes), 12)]
    q = ""
    if quant is not None:
        (si, zi), (so, zo) = quant
        q = (f"#define {var.upper()}_INPUT_SCALE {si!r}f\n#define {var.upper()}_INPUT_ZERO_POINT {zi}\n"
             f"#define {var.upper()}_OUTPUT_SCALE {so!r}f\n#define {var.upper()}_OUTPUT_ZERO_POINT {zo}\n")
    meta_s = "".join(f"/*   {k}: {v} */\n" for k, v in (meta or {}).items())
    Path(header_path).write_text(
        HEADER_NOTE.format(date=datetime.date.today().isoformat())
        + "/* TensorFlow Lite flatbuffer for TFLite Micro (Arduino: TensorFlowLite_ESP32 / ESP-IDF: esp-tflite-micro).\n"
          "   Inputs must be prepared exactly like dgx_model_mlp.h (median impute, (x-mean)/scale, clip +/-5) then quantised. */\n"
        + meta_s + f"#ifndef {var.upper()}_H\n#define {var.upper()}_H\n" + q
        + f"__attribute__((aligned(16))) static const unsigned char {var}[] = {{\n    "
        + ",\n    ".join(lines) + f"\n}};\nstatic const unsigned int {var}_len = {len(data)};\n#endif\n")
    return len(data)


# ------------------------------------------------------------------ DSP spec for the firmware port
def dsp_spec_header(path, fs_list=(125, 250, 500)):
    s = [_preamble("DGX_DSP_SPEC_H", "DSP constants of edge_features.py (feature-extractor port reference)", {})]
    for fs in fs_list:
        sos = ef.design_bandpass(fs)
        s.append(f"/* {fs} Hz: 0.5-40 Hz Butterworth band-pass, {len(sos)} biquads, rows = b0 b1 b2 a0 a1 a2 */\n")
        s.append(c_array("double", f"DGX_SOS_{fs}HZ", sos.ravel(), "double", 6))
    consts = {"PAD_S": ef.PAD_S, "SMOOTH_S": ef.SMOOTH_S, "AVG_S": ef.AVG_S, "THR_WEIGHT": ef.THR_WEIGHT,
              "MIN_LEN_WEIGHT": ef.MIN_LEN_WEIGHT, "MIN_DELAY_S": ef.MIN_DELAY_S, "SLOPE_FRAC": ef.SLOPE_FRAC,
              "SLOPE_REF_PCT": ef.SLOPE_REF_PCT, "Q_WIN_S": ef.Q_WIN_S, "S_WIN_S": ef.S_WIN_S,
              "P_WIN_START_S": ef.P_WIN_S[0], "P_WIN_END_S": ef.P_WIN_S[1], "T_WIN_START_S": ef.T_WIN_S[0],
              "T_WIN_END_S": ef.T_WIN_S[1], "SQI_MIN_BEATS": ef.SQI_MIN_BEATS, "SQI_HR_MIN": ef.SQI_HR_RANGE[0],
              "SQI_HR_MAX": ef.SQI_HR_RANGE[1], "SQI_MAX_RR_RATIO": ef.SQI_MAX_RR_RATIO,
              "BEAT_WIN_PRE_S": ef.BEAT_WIN_S[0], "BEAT_WIN_POST_S": ef.BEAT_WIN_S[1], "SQI_MIN_BEAT_CORR": ef.SQI_MIN_BEAT_CORR,
              "RECORD_SECONDS": 10.0}
    s.append("".join(f"#define DGX_{k} {float(v)!r}\n" for k, v in consts.items()))
    s.append("#endif\n")
    Path(path).write_text("".join(s))


# ------------------------------------------------------------------ C parity harness (any set of model headers)
def compile_and_run_parity(deploy_dir, headers, features_f32, compiler="clang"):
    """headers: list of (header file name, C prefix, n_features). features_f32: dict prefix -> (n, k) array.
    Builds a C program that scores every row with every header and returns {prefix: (score, calibrated)}."""
    deploy_dir = Path(deploy_dir)
    test_dir = deploy_dir / "parity_test"
    test_dir.mkdir(exist_ok=True)
    inc = "".join(f'#include "{h}"\n' for h, _, _ in headers)
    blocks = []
    for h, pre, k in headers:
        csv = test_dir / f"features_{pre.lower()}.csv"
        with open(csv, "w") as fh:
            for row in features_f32[pre]:
                fh.write(",".join("nan" if np.isnan(v) else f"{v:.9g}" for v in row) + "\n")
        blocks.append(f"""
    {{
        FILE *f = fopen("{csv}", "r");
        if (!f) {{ perror("{csv}"); return 1; }}
        float x[{pre}_N_FEATURES];
        while (fgets(line, sizeof line, f)) {{
            char *tok = strtok(line, ",");
            for (int i = 0; i < {pre}_N_FEATURES && tok; ++i, tok = strtok(NULL, ","))
                x[i] = (strncmp(tok, "nan", 3) == 0) ? NAN : strtof(tok, NULL);
            double s = {pre.lower()}_score(x);
            printf("{pre},%.17g,%.17g\\n", s, {pre.lower()}_calibrate(s));
        }}
        fclose(f);
    }}""")
    src = ("#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n#include <math.h>\n" + inc
           + "int main(void) {\n    char line[16384];" + "".join(blocks) + "\n    return 0;\n}\n")
    (test_dir / "parity.c").write_text(src)
    exe = test_dir / "parity"
    cmd = [compiler, "-std=c99", "-O2", "-Wall", "-Wextra", "-I", str(deploy_dir), str(test_dir / "parity.c"), "-o", str(exe), "-lm"]
    comp = subprocess.run(cmd, capture_output=True, text=True)
    if comp.returncode != 0:
        raise RuntimeError(comp.stderr)
    run = subprocess.run([str(exe)], capture_output=True, text=True, check=True)
    out = {}
    for line in run.stdout.strip().splitlines():
        pre, a, b = line.split(",")
        out.setdefault(pre, []).append((float(a), float(b)))
    return {k: np.array(v) for k, v in out.items()}, comp.stderr


# ------------------------------------------------------------------ golden vectors for the C++ feature extractor
def write_golden_vectors(out_dir, ids, signals_uv, features, fs):
    """signals_uv: (n, n_samples) device stream in microvolts; features: DataFrame (n rows, EDGE_ALL + SQI).
    Writes signals.csv (one record per row), features.csv (header row) for the host test of ecg_features.h."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    with open(out_dir / "signals_uv.csv", "w") as fh:
        for rid, x in zip(ids, signals_uv):
            fh.write(str(rid) + "," + ",".join(f"{v:.6f}" for v in x) + "\n")
    cols = list(ef.EDGE_ALL) + list(ef.SQI_FIELDS)
    f = features[cols].copy()
    f.insert(0, "ecg_id", list(ids))
    f["sqi_ok"] = f["sqi_ok"].astype(int)
    f.to_csv(out_dir / "features.csv", index=False, float_format="%.17g", na_rep="nan")
    (out_dir / "README.txt").write_text(
        f"Golden vectors for ecg_features.h: {len(ids)} records, {signals_uv.shape[1]} samples at {fs} Hz in microvolts "
        "(the stream the firmware feeds to the extractor). features.csv holds the Python reference output.\n")
