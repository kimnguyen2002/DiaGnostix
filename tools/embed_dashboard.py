#!/usr/bin/env python3
"""Embed the web dashboard into the DiaGnostix-ECG sketch.

Compresses firmware/web/index.html with gzip and writes it as a C byte array to
firmware/DiaGnostixECG/dashboard_html.h, which the firmware serves with
"Content-Encoding: gzip". Run this after every change to the dashboard.

Usage (from the repository root)
  python tools/embed_dashboard.py
"""

from __future__ import annotations

import gzip
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "firmware" / "web" / "index.html"
TARGET = ROOT / "firmware" / "DiaGnostixECG" / "dashboard_html.h"


def main() -> int:
    html = SOURCE.read_bytes()
    data = gzip.compress(html, compresslevel=9, mtime=0)  # mtime=0: reproducible output
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    TARGET.write_text(
        "// AUTO-GENERATED by tools/embed_dashboard.py from firmware/web/index.html.\n"
        "// Do not edit by hand: change index.html and run the script again.\n"
        "#pragma once\n\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n\n"
        f"// gzip-compressed dashboard ({len(html)} bytes uncompressed).\n"
        "static const uint8_t kDashboardHtmlGz[] = {\n"
        + "".join(f"  {r},\n" for r in rows)
        + "};\n"
        f"static const size_t kDashboardHtmlGzLen = {len(data)};\n"
    )
    print(f"{SOURCE.relative_to(ROOT)}: {len(html)} B -> {len(data)} B gzip -> {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
